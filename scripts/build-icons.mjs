// Builds public/js/icons.js from lucide-static (ISC licence). Run: node scripts/build-icons.mjs
import fs from 'node:fs';

const NAMES = ['message-circle', 'dices', 'gamepad-2', 'lock', 'flame', 'shield-check', 'arrow-up', 'lightbulb', 'flag', 'skip-forward', 'x',
  'arrow-left', 'arrow-right', 'heart', 'users', 'smartphone', 'link', 'copy', 'share-2', 'trophy', 'sparkles', 'moon-star', 'zap', 'music',
  'clapperboard', 'book-open', 'code-xml', 'utensils', 'plane', 'palette', 'dumbbell', 'laugh', 'user-round', 'trash-2', 'check', 'brain',
  'megaphone', 'user-round-search', 'heart-handshake', 'target', 'drama', 'cherry', 'smile', 'frown', 'angry', 'party-popper', 'sprout',
  'hand', 'radio', 'wind', 'eye-off', 'lock-keyhole', 'refresh-cw', 'circle-help', 'info', 'plus', 'send', 'user-x', 'flame-kindling', 'waves', 'bolt', 'ghost', 'image', 'eye', 'timer', 'qr-code', 'bug', 'message-square-heart', 'download', 'external-link'];

const dir = 'node_modules/lucide-static/icons/';
const out = {}, missing = [];
for (const n of NAMES) {
  const f = dir + n + '.svg';
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
const src = `// GENERATED by scripts/build-icons.mjs from lucide-static (ISC). Do not edit by hand.
export const ICONS = ${JSON.stringify(out, null, 1)};

/** returns an inline-SVG <span class="ic"> that inherits currentColor */
export function icon(name, size = 22, extra = '') {
  const s = document.createElement('span');
  s.className = 'ic' + (extra ? ' ' + extra : '');
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + (ICONS[name] || ICONS['circle-help']) + '</svg>';
  return s;
}
`;
fs.writeFileSync('public/js/icons.js', src);
console.log('icons:', Object.keys(out).length, missing.length ? 'MISSING: ' + missing.join(', ') : 'all found');
